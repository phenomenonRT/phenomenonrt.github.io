#!/usr/bin/env python3
"""Проверка профиля fivem на настоящей библиотеке ENet.

Поднимает минимальный ENet-сервер (enet_server.c), отправляет ему I2–I5,
сгенерированные mimicry.py, и проверяет, что ENet принял CONNECT и доставил
payload пакетов I3/I4/I5 на нужных каналах. Подтверждает раскладку байтов
ENet, но не сходство с трафиком FiveM и не работу DPI.

Сборка и запуск (нужны gcc и git):
    git clone --depth 1 https://github.com/lsalzman/enet.git
    gcc -O1 -Ienet/include verify/enet_server.c enet/callbacks.c enet/compress.c \
        enet/host.c enet/list.c enet/packet.c enet/peer.c enet/protocol.c enet/unix.c \
        -o verify/enet_server
    python verify/enet_check.py
"""
import sys, re, socket, struct, subprocess, time, base64, os
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))
import mimicry

D = os.environ.get("ENET_SERVER_DIR", HERE)  # directory with the compiled enet_server binary
KEY = base64.b64encode(b"0123456789abcdef0123456789abcdef").decode()
TAG = re.compile(r"<([a-z]+)(?:\s+([^>]*))?>")

def render(spec):
    out = b""
    for m in TAG.finditer(spec):
        t, a = m.group(1), (m.group(2) or "").strip()
        out += bytes.fromhex(a[2:]) if t == "b" else os.urandom(int(a))
    return out

def run_case(seed, mode, mtu, port):
    r = mimicry.generate("fivem", 2, mode, mtu, "127.0.0.1", port, seed, header_key=KEY)
    P = {k: render(v) for k, v in r["params"].items() if re.fullmatch(r"i[1-5]", k)}
    srv = subprocess.Popen([f"{D}/enet_server", str(port), "3500"], stdout=subprocess.PIPE, text=True)
    assert srv.stdout.readline().strip() == "READY"
    sock = socket.socket(socket.AF_INET, socket.SOCK_DGRAM); sock.settimeout(2)
    dst = ("127.0.0.1", port)
    problems = []

    # --- I2: ENet CONNECT, sent exactly as generated
    sock.sendto(P["i2"], dst)
    try:
        v, _ = sock.recvfrom(4096)
    except socket.timeout:
        srv.kill(); return ["no VERIFY_CONNECT: ENet did not accept the generated CONNECT"], r, []
    hdr = struct.unpack(">H", v[:2])[0]
    off = 2
    sent_time = 0
    if hdr & 0x8000:
        sent_time = struct.unpack(">H", v[2:4])[0]; off = 4
    cmd, chan, seq = v[off], v[off+1], struct.unpack(">H", v[off+2:off+4])[0]
    if cmd & 0x0F != 3: problems.append(f"expected VERIFY_CONNECT(3), got command {cmd:#x}")
    body = v[off+4:]
    peer_idx, in_sess, out_sess = struct.unpack(">HBB", body[:4])
    # session bits the server expects in later datagrams = outgoingSessionID of its verify
    hdr_bits = peer_idx | ((out_sess & 3) << 12)
    # --- ACK the verify, like a real client
    ack = struct.pack(">HH", 0x8000 | hdr_bits, 0x1234) + struct.pack(">BBH", 0x81, chan, seq) + struct.pack(">HH", seq, sent_time)
    sock.sendto(ack, dst); time.sleep(0.15)

    # --- I3/I4/I5: generated bytes; only the 2-byte peerID/session field is set to what the
    # server handed out (a real client learns it from VERIFY_CONNECT; the generator cannot).
    for k in ("i3", "i4", "i5"):
        pkt = struct.pack(">H", 0x8000 | hdr_bits) + P[k][2:]
        sock.sendto(pkt, dst); time.sleep(0.1)
    out = srv.communicate(timeout=10)[0]
    return problems, r, out.splitlines()

